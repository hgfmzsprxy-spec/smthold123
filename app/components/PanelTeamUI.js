export function TeamPermissionEditor({ kind = "reseller", value, onChange, applications = [] }) {
  const groups = kind === "admin" ? ADMIN_PERM_GROUPS : RESELLER_PERM_GROUPS;
  const perms = normalizePermissions(value, kind);

  function toggle(key) {
    onChange({ ...perms, [key]: !perms[key] });
  }

  function setAppsAll(next) {
    onChange({ ...perms, "apps.all": next, "apps.ids": next ? [] : perms["apps.ids"] });
  }

  function toggleAppId(appId) {
    const id = String(appId);
    const set = new Set(perms["apps.ids"] || []);
    if (set.has(id)) set.delete(id);
    else set.add(id);
    onChange({ ...perms, "apps.all": false, "apps.ids": [...set] });
  }

  return (
    <div className={styles.teamPermEditor}>
      {groups.map((group) => (
        <div key={group.id} className={styles.teamPermGroup}>
          <strong className={styles.teamPermGroupTitle}>{group.label}</strong>
          <div className={styles.teamPermGrid}>
            {group.keys.map((key) => (
              <label
                key={key}
                className={`${styles.teamPermItem}${perms[key] ? ` ${styles.teamPermItemOn}` : ""}`}
              >
                <input type="checkbox" checked={Boolean(perms[key])} onChange={() => toggle(key)} />
                <span className={styles.teamPermCheck} aria-hidden="true">
                  {perms[key] ? <Check size={11} strokeWidth={3} /> : null}
                </span>
                <span>{permissionLabel(key)}</span>
              </label>
            ))}
          </div>
        </div>
      ))}

      <div className={styles.teamPermGroup}>
        <strong className={styles.teamPermGroupTitle}>Application access</strong>
        <label className={`${styles.teamPermItem}${perms["apps.all"] ? ` ${styles.teamPermItemOn}` : ""}`}>
          <input
            type="checkbox"
            checked={Boolean(perms["apps.all"])}
            onChange={(event) => setAppsAll(event.target.checked)}
          />
          <span className={styles.teamPermCheck} aria-hidden="true">
            {perms["apps.all"] ? <Check size={11} strokeWidth={3} /> : null}
          </span>
          <span>All applications</span>
        </label>
        {!perms["apps.all"] && applications.length ? (
          <div className={styles.teamPermGrid}>
            {applications.map((app) => {
              const id = String(app.id || app.app_id || "");
              const on = (perms["apps.ids"] || []).includes(id);
              return (
                <label key={id} className={`${styles.teamPermItem}${on ? ` ${styles.teamPermItemOn}` : ""}`}>
                  <input type="checkbox" checked={on} onChange={() => toggleAppId(id)} />
                  <span className={styles.teamPermCheck} aria-hidden="true">
                    {on ? <Check size={11} strokeWidth={3} /> : null}
                  </span>
                  <span>{app.name || id}</span>
                </label>
              );
            })}
          </div>
        ) : null}
      </div>

      <div className={styles.teamPermGroup}>
        <strong className={styles.teamPermGroupTitle}>Limits</strong>
        <div className={styles.teamLimitRow}>
          <label>
            <span>Max generate qty</span>
            <input
              type="number"
              min="1"
              max="200"
              placeholder="Unlimited"
              value={perms["limits.generate_max_qty"] ?? ""}
              onChange={(event) =>
                onChange({
                  ...perms,
                  "limits.generate_max_qty": event.target.value === "" ? null : Number(event.target.value),
                })
              }
            />
          </label>
          <label>
            <span>Generate per day</span>
            <input
              type="number"
              min="1"
              max="10000"
              placeholder="Unlimited"
              value={perms["limits.generate_per_day"] ?? ""}
              onChange={(event) =>
                onChange({
                  ...perms,
                  "limits.generate_per_day": event.target.value === "" ? null : Number(event.target.value),
                })
              }
            />
          </label>
        </div>
      </div>
    </div>
  );
}

export function TeamMemberDrawer({
  open,
  title,
  discordUserId,
  onDiscordUserIdChange,
  permissions,
  onPermissionsChange,
  kind,
  applications,
  busy,
  error,
  onClose,
  onSubmit,
  mode = "add",
}) {
  const [step, setStep] = useState("form");
  const [accepted, setAccepted] = useState(false);
  const [localError, setLocalError] = useState("");

  useEffect(() => {
    if (!open) return;
    setStep("form");
    setAccepted(false);
    setLocalError("");
  }, [open, mode, title]);

  if (!open) return null;

  const confirmTitle = mode === "add" ? "Confirm team invite" : "Confirm permission changes";
  const displayError = localError || error;

  function handleClose() {
    setStep("form");
    setAccepted(false);
    setLocalError("");
    onClose();
  }

  function handlePrimarySubmit(event) {
    event.preventDefault();
    setLocalError("");
    if (mode === "add" && !String(discordUserId || "").trim()) {
      setLocalError("Enter a valid Discord User ID.");
      return;
    }
    setAccepted(false);
    setStep("confirm");
  }

  function handleConfirmSubmit(event) {
    event.preventDefault();
    if (!accepted) {
      setLocalError("Accept the responsibility notice to continue.");
      return;
    }
    setLocalError("");
    onSubmit();
  }

  return (
    <div className={`${styles.sideDrawer} ${styles.sideDrawerOpen}`} onClick={handleClose}>
      <div
        className={`${styles.sideDrawerPanel} ${styles.sideDrawerPanelWide} ${styles.teamMemberDrawerPanel}`}
        onClick={(event) => event.stopPropagation()}
      >
        <div className={`${styles.tableHeader} ${styles.teamMemberDrawerHeader}`}>
          <h2 className={styles.noSpaceBottom}>{step === "confirm" ? confirmTitle : title}</h2>
          <button className={styles.closeButton} type="button" onClick={handleClose} aria-label="Close">
            <X size={18} />
          </button>
        </div>
        <div className={`${styles.tableContent} ${styles.teamMemberDrawerBody}`}>
          {step === "form" ? (
            <form
              className={`${styles.formPad} ${styles.teamMemberDrawerForm}`}
              onSubmit={handlePrimarySubmit}
            >
              {mode === "add" ? (
                <div className={styles.group}>
                  <label htmlFor="team-discord-user-id">Discord User ID</label>
                  <input
                    id="team-discord-user-id"
                    type="text"
                    inputMode="numeric"
                    placeholder="123456789012345678"
                    value={discordUserId}
                    onChange={(event) => onDiscordUserIdChange(event.target.value.replace(/\D/g, "").slice(0, 20))}
                    required
                  />
                </div>
              ) : null}

              <TeamPermissionEditor
                kind={kind}
                value={permissions}
                onChange={onPermissionsChange}
                applications={applications}
              />

              {displayError ? <div className={`${styles.message} ${styles.messageerror}`}>{displayError}</div> : null}

              <div className={styles.formActions}>
                <button type="button" className={styles.secondaryButton} onClick={handleClose}>
                  Cancel
                </button>
                <button type="submit" className={styles.primaryButton} disabled={busy}>
                  <Plus size={14} />
                  {mode === "add" ? "Add member" : "Save permissions"}
                </button>
              </div>
            </form>
          ) : (
            <form
              className={`${styles.formPad} ${styles.teamMemberDrawerForm} ${styles.teamMemberConfirmForm}`}
              onSubmit={handleConfirmSubmit}
            >
              <div className={styles.teamMemberLiabilityAlert} role="alert">
                <AlertTriangle size={18} aria-hidden="true" />
                <div>
                  <strong>Responsibility notice</strong>
                  <p>
                    unbanhwid.com does not accept responsibility for team members you invite, the permissions you grant
                    them, or any actions they take while using your panel access. You remain fully responsible for your
                    team, account security, and any resulting activity or abuse.
                  </p>
                </div>
              </div>

              <label
                className={`checkout-terms${accepted ? " is-checked" : ""} ${styles.teamMemberLiabilityCheck}`}
              >
                <input
                  type="checkbox"
                  checked={accepted}
                  disabled={busy}
                  onChange={(event) => {
                    setAccepted(event.target.checked);
                    if (event.target.checked) setLocalError("");
                  }}
                />
                <span className="checkout-terms-box" aria-hidden="true">
                  {accepted ? <Check size={14} strokeWidth={3} /> : null}
                </span>
                <span className="checkout-terms-text">
                  I understand and accept full responsibility for this team member and the access I grant.
                </span>
              </label>

              {displayError ? <div className={`${styles.message} ${styles.messageerror}`}>{displayError}</div> : null}

              <div className={styles.formActions}>
                <button
                  type="button"
                  className={styles.secondaryButton}
                  onClick={() => {
                    setStep("form");
                    setAccepted(false);
                    setLocalError("");
                  }}
                  disabled={busy}
                >
                  Back
                </button>
                <button type="submit" className={styles.primaryButton} disabled={busy || !accepted}>
                  <Plus size={14} />
                  {busy ? "Saving…" : mode === "add" ? "Confirm & add member" : "Confirm & save"}
                </button>
              </div>
            </form>
          )}
        </div>
      </div>
    </div>
  );
}

