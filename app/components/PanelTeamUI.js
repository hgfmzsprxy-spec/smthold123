function discordFallbackAvatarUrl(discordUserId) {
  const id = String(discordUserId || "").trim();
  if (!/^\d{17,20}$/.test(id)) return null;
  try {
    const index = Number(BigInt(id) >> 22n) % 6;
    return `https://cdn.discordapp.com/embed/avatars/${index}.png`;
  } catch {
    return null;
  }
}

export function getTransactionStaffGenerator(entry) {
  if (!entry || typeof entry !== "object") return null;
  const meta = entry.meta && typeof entry.meta === "object" ? entry.meta : {};
  const hasStaff =
    entry.actor === "reseller_staff" ||
    meta.staff_team_member_id ||
    meta.staff_discord_user_id ||
    meta.staff_discord_username;
  if (!hasStaff) return null;
  const discordUserId = meta.staff_discord_user_id || null;
  return {
    team_member_id: meta.staff_team_member_id || null,
    discord_user_id: discordUserId,
    discord_username: meta.staff_discord_username || null,
    discord_avatar_url:
      meta.staff_discord_avatar_url || discordFallbackAvatarUrl(discordUserId) || null,
    generated_at: meta.staff_generated_at || entry.created_at || null,
  };
}

export function StaffGeneratorMarker({
  generator,
  subtitle = "Generated this key",
  title = "Generated by team staff",
}) {
  const [open, setOpen] = useState(false);
  const [pos, setPos] = useState(null);
  const buttonRef = useRef(null);
  const cardRef = useRef(null);

  useEffect(() => {
    if (!open) {
      setPos(null);
      return undefined;
    }

    function updatePosition() {
      const button = buttonRef.current;
      if (!button) {
        setPos(null);
        return;
      }
      const rect = button.getBoundingClientRect();
      const cardWidth = 240;
      const gap = 8;
      const left = Math.min(rect.right + gap, window.innerWidth - cardWidth - 12);
      const top = Math.min(Math.max(12, rect.top + rect.height / 2), window.innerHeight - 12);
      setPos({ top, left: Math.max(12, left) });
    }

    function handlePointerDown(event) {
      if (cardRef.current?.contains(event.target)) return;
      if (buttonRef.current?.contains(event.target)) return;
      setOpen(false);
    }

    function handleKeyDown(event) {
      if (event.key === "Escape") setOpen(false);
    }

    updatePosition();
    window.addEventListener("resize", updatePosition);
    window.addEventListener("scroll", updatePosition, true);
    document.addEventListener("mousedown", handlePointerDown);
    document.addEventListener("keydown", handleKeyDown);
    return () => {
      window.removeEventListener("resize", updatePosition);
      window.removeEventListener("scroll", updatePosition, true);
      document.removeEventListener("mousedown", handlePointerDown);
      document.removeEventListener("keydown", handleKeyDown);
    };
  }, [open]);

  if (!generator) return null;

  return (
    <>
      <div className={styles.licenseStaffGenWrap}>
        <button
          type="button"
          ref={buttonRef}
          className={`${styles.licenseStaffGenButton}${open ? ` ${styles.licenseStaffGenButtonOpen}` : ""}`}
          title={title}
          aria-label={title}
          aria-expanded={open}
          onClick={() => setOpen((current) => !current)}
        >
          <Users size={14} />
        </button>
      </div>
      {open && pos && typeof document !== "undefined"
        ? createPortal(
            <div
              ref={cardRef}
              className={`${styles.licenseStaffGenCard} ${styles.licenseStaffGenCardPortal}`}
              role="dialog"
              style={{ top: pos.top, left: pos.left }}
            >
              <div className={styles.licenseStaffGenCardHead}>
                {generator.discord_avatar_url ? (
                  <img
                    src={generator.discord_avatar_url}
                    alt=""
                    className={styles.licenseStaffGenAvatar}
                  />
                ) : (
                  <span className={styles.licenseStaffGenAvatarFallback} aria-hidden="true">
                    <Users size={14} />
                  </span>
                )}
                <div className={styles.licenseStaffGenMeta}>
                  <strong>{generator.discord_username || "Team staff"}</strong>
                  <span>{subtitle}</span>
                </div>
              </div>
              <div className={styles.licenseStaffGenRow}>
                <span>When</span>
                <strong>{formatDisplayDateTime(generator.generated_at)}</strong>
              </div>
              {generator.discord_user_id ? (
                <div className={styles.licenseStaffGenRow}>
                  <span>Discord ID</span>
                  <strong className={styles.teamMonoCell}>{generator.discord_user_id}</strong>
                </div>
              ) : null}
            </div>,
            document.body
          )
        : null}
    </>
  );
}

